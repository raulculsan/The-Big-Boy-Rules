/* Small list assets; the catalog's original front/back always remain untouched. */
import {readFile, writeFile, mkdir, stat, unlink} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {dirname, resolve, basename} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'icons/cards/thumbnails');
const manifestFile = resolve(directory, 'manifest.json');
const WIDTH = 360, QUALITY = 78, VERSION = 1;
function run(command, args) {
  return new Promise((accept, reject) => {
    const child = spawn(command, args, {stdio: ['ignore', 'ignore', 'pipe']});
    let errorText = '';
    child.stderr.on('data', chunk => { errorText += chunk; });
    child.once('error', reject);
    child.once('exit', code => code === 0 ? accept() : reject(new Error(`${command}: ${errorText || code}`)));
  });
}
export async function buildCardThumbnails() {
  await mkdir(directory, {recursive: true});
  const catalog = await readFile(resolve(root, 'card-collection.js'), 'utf8');
  const sources = [...new Set([...catalog.matchAll(/front:\s*['"](icons\/cards\/[^'"]+\.png)['"]/g)].map(match => match[1]))].sort();
  let previous = {};
  try { previous = JSON.parse(await readFile(manifestFile, 'utf8')); } catch {}
  const manifest = {}, mapping = {};
  let generated = 0, originalBytes = 0, thumbnailBytes = 0;
  for (const source of sources) {
    const input = resolve(root, source), info = await stat(input);
    const target = `icons/cards/thumbnails/${basename(source, '.png')}.jpg`, output = resolve(root, target);
    const fingerprint = `${VERSION}:${WIDTH}:${QUALITY}:${info.size}:${info.mtimeMs}`;
    let exists = true;
    try { await stat(output); } catch { exists = false; }
    if (!exists || previous[source]?.fingerprint !== fingerprint) {
      if (process.platform === 'darwin') {
        await run('/usr/bin/sips', ['--resampleWidth', String(WIDTH), '--setProperty', 'format', 'jpeg', '--setProperty', 'formatOptions', String(QUALITY), input, '--out', output]);
      } else {
        // ImageMagick is the build prerequisite on Linux/Windows. Existing
        // generated thumbnails need no image tool when source files are unchanged.
        await run('magick', [input, '-resize', `${WIDTH}x`, '-quality', String(QUALITY), output]);
      }
      generated++;
    }
    originalBytes += info.size; thumbnailBytes += (await stat(output)).size;
    manifest[source] = {target, fingerprint}; mapping[source] = target;
  }
  // Remove obsolete generated variants when a published design changes, without
  // touching originals or arbitrary files outside this generated directory.
  for (const [source, entry] of Object.entries(previous)) {
    if (manifest[source] || typeof entry.target !== 'string') continue;
    const stale = resolve(root, entry.target);
    if (dirname(stale) !== directory || !stale.endsWith('.jpg')) continue;
    try { await unlink(stale); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  const json = JSON.stringify(manifest, null, 2) + '\n';
  if (JSON.stringify(previous, null, 2) + '\n' !== json) await writeFile(manifestFile, json);
  const runtime = `/* Generated by scripts/build-card-thumbnails.mjs. Do not edit. */\nglobalThis.CardThumbnails = Object.freeze(${JSON.stringify(mapping, null, 2)});\n`;
  const runtimeFile = resolve(root, 'card-thumbnails.js');
  let existing = '';
  try { existing = await readFile(runtimeFile, 'utf8'); } catch {}
  if (existing !== runtime) await writeFile(runtimeFile, runtime);
  console.log(`Card thumbnails: ${sources.length} assets, ${generated} generated; ${(originalBytes / 1e6).toFixed(1)} MB originals → ${(thumbnailBytes / 1e6).toFixed(1)} MB list images.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildCardThumbnails();
