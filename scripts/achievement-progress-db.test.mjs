test('rolled-back messages do not count; attachments count and new goals never inherit earlier activity',async()=>{
  await db.exec('begin');
  await query("insert into messages(user_id,body) values($1,'Se cancelará')",[bob]);
  assert.equal((await progress(messageRule,bob)).current_value,1);
  await db.exec('rollback');
  assert.equal(await progress(messageRule,bob),undefined);
  await asUser(bob,()=>query("insert into messages(user_id,body,attachment_url) values($1,'','https://example.test/audio.m4a')",[bob]));
  assert.equal((await progress(messageRule,bob)).current_value,1);
  const newGoal=await create('group_messages',50,'Una nueva etapa');
  assert.equal(await progress(newGoal,bob),undefined);
  await send(bob);
  assert.equal((await progress(newGoal,bob)).current_value,1);
  assert.equal((await progress(messageRule,bob)).current_value,1,'attachment and text share the same daily limit');
});

test('RLS exposes only own progress, even to administrators; ledger and counters cannot be forged',async()=>{
  await asUser(alice,async()=>{
    const rows=await query('select * from achievement_progress');
    assert.ok(rows.length>=3); assert.ok(rows.every(r=>r.user_id===alice));
    assert.equal((await query('select * from achievement_progress where user_id=$1',[bob])).length,0);
    await assert.rejects(query('select * from achievement_progress_events'),/permission denied/);
    await assert.rejects(query('update achievement_progress set current_value=999'),/permission denied/);
    await assert.rejects(query('delete from achievement_rules'),/permission denied/);
    await assert.rejects(query("select record_achievement_activity($1,'group_messages','forged',null)",[alice]),/permission denied/);
    await assert.rejects(query('select track_group_achievement_activity()'),/permission denied/);
    await assert.rejects(query('select record_daily_app_visit($1::uuid)',[bob]),/does not exist/);
    await assert.rejects(query("insert into messages(user_id,body) values($1,'Forged sender')",[bob]),/row-level security/);
  });
  assert.equal((await asUser(admin,()=>query('select * from achievement_progress'))).length,0);
  await db.exec('set role anon');
  try {
    await assert.rejects(query('select * from achievement_progress'),/permission denied/);
    await assert.rejects(query("select create_automatic_achievement('Hack','','gold','group_messages',1)"),/permission denied/);
    await assert.rejects(query('select record_daily_app_visit()'),/permission denied/);
  } finally { await db.exec('reset role'); }
});

