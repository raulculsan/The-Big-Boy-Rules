const sql = file => readFile(new URL('../'+file,import.meta.url),'utf8');
const query = async (text, params=[]) => (await db.query(text,params)).rows;
async function asUser(id, fn) {
  await db.exec('set role authenticated');
  await query("select set_config('request.jwt.claim.sub', $1, false)",[id]);
  try { return await fn(); } finally { await db.exec('reset role'); }
}
const create = (metric,target,name='Objetivo de prueba') => asUser(admin, async () =>
  (await query('select public.create_automatic_achievement($1,$2,$3,$4,$5) as id',[name,'Descripción','gold',metric,target]))[0].id);
const send = (user,createdAt='2020-01-01') => asUser(user,()=>query('insert into public.messages(user_id,body,created_at) values ($1,$2,$3) returning id',[user,'Mensaje de prueba',createdAt]));
const progress = async (id,user) => (await query('select * from public.achievement_progress where achievement_id=$1 and user_id=$2',[id,user]))[0];
let messageRule,dayRule,profileRule;

