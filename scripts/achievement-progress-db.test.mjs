// Collection extension tests run after the original goals, on the same isolated DB.

test('only admins can create validated atomic objectives; invalid creation leaves no rows', async () => {
  await assert.rejects(asUser(alice,()=>query("select create_automatic_achievement('Hack','','gold','group_messages',1)")),/permiso/);
  const before=(await query('select count(*)::int as n from achievements'))[0].n;
  for (const [metric,target] of [['no_such_metric',1],['group_messages',0],['group_messages',100001],['profile_completed',2],['group_messages',null],[null,1]]) {
    await assert.rejects(create(metric,target));
  }
  assert.equal((await query('select count(*)::int as n from achievements'))[0].n,before);
  messageRule=await create('group_messages',3);
  dayRule=await create('group_active_days',3,'Días distintos');
  profileRule=await create('profile_completed',1,'Tu identidad');
  assert.equal(await progress(messageRule,alice),undefined,'historical messages do not count');
});

test('profile objective recognizes complete profiles once, excludes hidden and supports future members',async()=>{
  assert.equal((await progress(profileRule,bob)).current_value,1);
  assert.ok((await progress(profileRule,bob)).completed_at);
  assert.equal(await progress(profileRule,hidden),undefined);
  await asUser(alice,()=>query("update profiles set bio='Mi bio', avatar_url='https://example.test/a.png' where id=$1",[alice]));
  assert.equal((await progress(profileRule,alice)).current_value,1);
  await asUser(alice,()=>query("update profiles set bio='Otra bio' where id=$1",[alice]));
  assert.equal((await query('select count(*)::int as n from achievement_awards where achievement_id=$1 and user_id=$2',[profileRule,alice]))[0].n,1);
  const newcomer='00000000-0000-0000-0000-000000000005';
  await query("insert into profiles(id,display_name,avatar_url,bio) values($1,'Nuevo','https://example.test/new.png','Hola')",[newcomer]);
  assert.equal((await progress(profileRule,newcomer)).current_value,1);
});

test('messages advance only the sender; edits, deletion and reinsertion do not duplicate an event',async()=>{
  const [{id}]=await send(alice);
  assert.equal((await progress(messageRule,alice)).current_value,1);
  assert.equal(await progress(messageRule,bob),undefined);
  await asUser(alice,()=>query("update messages set body='Editado' where id=$1",[id]));
  assert.equal((await progress(messageRule,alice)).current_value,1);
  await asUser(alice,()=>query('delete from messages where id=$1',[id]));
  await asUser(alice,()=>query("insert into messages(id,user_id,body) values($1,$2,'Reintentado')",[id,alice]));
  assert.equal((await progress(messageRule,alice)).current_value,1);
  assert.equal(await progress(dayRule,alice),undefined,'writing is not an app login');
});

test('only one group message counts per day; visits count without messages and neither trusts client dates',async()=>{
  await send(alice,'2099-01-01');
  await send(alice,'1999-01-01');
  assert.equal((await progress(messageRule,alice)).current_value,1);
  assert.equal(await progress(dayRule,alice),undefined);
  for (let i=0;i<4;i++) await asUser(alice,()=>query('select record_daily_app_visit()'));
  await asUser(bob,()=>query('select record_daily_app_visit()'));
  assert.equal((await progress(dayRule,alice)).current_value,1,'several logins or devices today count once');
  assert.equal((await progress(dayRule,bob)).current_value,1,'no message required');
  assert.equal(await progress(messageRule,bob),undefined);
  // Simulate trusted server events on distinct days; clients cannot call this helper.
  await query("select record_achievement_activity($1,'group_messages','day:2026-01-01',$2)",[alice,messageRule]);
  await query("select record_achievement_activity($1,'group_messages','day:2026-01-02',$2)",[alice,messageRule]);
  assert.equal((await progress(messageRule,alice)).current_value,3);
  const first=(await progress(messageRule,alice)).completed_at;
  await send(alice);
  assert.equal((await progress(messageRule,alice)).current_value,3);
  assert.equal(String((await progress(messageRule,alice)).completed_at),String(first));
  assert.equal((await query('select count(*)::int as n from achievement_awards where achievement_id=$1 and user_id=$2',[messageRule,alice]))[0].n,1);
  assert.equal((await progress(dayRule,alice)).current_value,1);
  // Simulate the trusted trigger firing on other days, never through an authenticated RPC.
  await query("select record_achievement_activity($1,'group_active_days','day:2026-01-01',$2)",[alice,dayRule]);
  await query("select record_achievement_activity($1,'group_active_days','day:2026-01-01',$2)",[alice,dayRule]);
  assert.equal((await progress(dayRule,alice)).current_value,2);
  await query("select record_achievement_activity($1,'group_active_days','day:2026-01-09',$2)",[alice,dayRule]);
  assert.equal((await progress(dayRule,alice)).current_value,3,'days need not be consecutive');
});

