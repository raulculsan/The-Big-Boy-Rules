-- Vincula automáticamente las cuentas creadas desde el panel con los perfiles.
create or replace function public.handle_new_big_boy()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
declare
  uname text := split_part(new.email, '@', 1);
  legacy smallint;
  visible_name text;
  member_role text := 'member';
begin
  legacy := case uname
    when 'kike' then 1 when 'lizzy' then 2 when 'raul' then 3
    when 'mario' then 4 when 'miguelangel' then 5 when 'almudena' then 6
    when 'carlos' then 7 when 'albertovelasco' then 8 when 'caonaboalbero' then 9
  end;
  if legacy is null then return new; end if;
  visible_name := case uname
    when 'kike' then 'Kike' when 'lizzy' then 'Lizzy' when 'raul' then 'Raúl'
    when 'mario' then 'Mario' when 'miguelangel' then 'Miguel Ángel'
    when 'almudena' then 'Almudena' when 'carlos' then 'Carlos'
    when 'albertovelasco' then 'Alberto Velasco' when 'caonaboalbero' then 'Caonabo Albero'
  end;
  if uname = 'kike' then member_role := 'admin'; end if;
  insert into public.profiles (id, legacy_id, username, display_name, nickname, bio, tags, role)
  values (new.id, legacy, uname, visible_name, 'The Big Boy', 'Miembro de The Big Boy Rules.',
    array['Comunidad', 'Momentos', 'Grupo'], member_role)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_big_boy();
