create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id smallint unique not null check (legacy_id between 1 and 9),
  username text unique not null,
  display_name text not null,
  nickname text not null default 'The Big Boy',
  bio text not null default '',
  tags text[] not null default '{}',
  avatar_url text,
  role text not null default 'member' check (role in ('admin', 'member')),
  updated_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id smallint not null references public.profiles(legacy_id),
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);

alter table public.messages add column if not exists attachment_url text;
alter table public.messages add column if not exists attachment_name text;
alter table public.messages add column if not exists attachment_type text;
alter table public.messages add column if not exists attachment_size bigint;
alter table public.messages drop constraint if exists messages_body_check;
alter table public.messages add constraint messages_body_check check (
  char_length(body) <= 1200 and (char_length(trim(body)) > 0 or attachment_url is not null)
);

create table if not exists public.moments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id smallint not null references public.profiles(legacy_id),
  caption text not null default '' check (char_length(caption) <= 300),
  media_url text not null,
  media_type text not null check (media_type in ('image', 'video')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours')
);

create table if not exists public.profile_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id smallint not null references public.profiles(legacy_id),
  caption text not null default '' check (char_length(caption) <= 300),
  media_url text not null,
  media_type text not null check (media_type in ('image', 'video')),
  created_at timestamptz not null default now()
);

create table if not exists public.private_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 1200),
  created_at timestamptz not null default now(),
  check (sender_id <> recipient_id)
);

create table if not exists public.group_events (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 80),
  description text not null default '' check (char_length(description) <= 500),
  starts_at timestamptz not null,
  ends_at timestamptz,
  location text not null default '' check (char_length(location) <= 120),
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at is null or ends_at >= starts_at)
);

create table if not exists public.site_settings (
  key text primary key,
  value text not null default '',
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

